// Writes .env.test.local for the DB test suite from the running local
// Supabase instance, so tests never pick up .env.local (which may point at
// Supabase Cloud). Usage: node scripts/write-test-env.mjs
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";

let out;
try {
  out = execFileSync("npx", ["supabase", "status", "-o", "env"], { encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] });
} catch {
  console.error("Local Supabase is not running. Start it with `npx supabase start`.");
  process.exit(1);
}

const status = Object.fromEntries(
  out
    .split("\n")
    .map((line) => line.match(/^([A-Z_]+)="?(.*?)"?$/))
    .filter(Boolean)
    .map((m) => [m[1], m[2]]),
);

const required = {
  NEXT_PUBLIC_SUPABASE_URL: "API_URL",
  NEXT_PUBLIC_SUPABASE_ANON_KEY: "ANON_KEY",
  SUPABASE_SERVICE_ROLE_KEY: "SERVICE_ROLE_KEY",
  // Direct Postgres access for catalog checks (RLS guard, grants).
  SUPABASE_DB_URL: "DB_URL",
};
const lines = Object.entries(required).map(([name, key]) => {
  if (!status[key]) {
    console.error(`\`supabase status\` did not report ${key}.`);
    process.exit(1);
  }
  return `${name}=${status[key]}`;
});

writeFileSync(".env.test.local", `# Generated by scripts/write-test-env.mjs - local Supabase only.\n${lines.join("\n")}\n`);
console.log(`Wrote .env.test.local for ${status.API_URL}`);
